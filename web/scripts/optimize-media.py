"""Generate responsive previews with Pillow; preserve all original media files."""

import json
import re
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / "public"
OUTPUT = PUBLIC / "media" / "optimized"
PATTERN = re.compile(r"media/[\w/-]+\.(?:webp|jpg|jpeg|png)")


def main() -> None:
    """Bake EXIF orientation into pixels and emit a typed preview manifest."""
    files = [ROOT / "src/data/works.ts", *sorted((ROOT / "src/content/works").glob("*.md"))]
    sources = {match for file in files for match in PATTERN.findall(file.read_text(encoding="utf-8"))}
    sources.update(f"media/haoyang-{name}.jpg" for name in ["sunglasses", "portrait", "coast", "outdoors"])
    manifest: dict[str, dict[str, str | int]] = {}
    original_bytes = 0
    preview_bytes = {640: 0, 1280: 0}
    for source in sorted(sources):
        path = PUBLIC / source
        with Image.open(path) as original:
            # JPEG display orientation must survive removal of metadata.
            upright = ImageOps.exif_transpose(original).convert("RGB")
            entry: dict[str, str | int] = {"width": upright.width, "height": upright.height}
            for width, label in [(640, "small"), (1280, "large")]:
                size = min(width, upright.width)
                preview = upright.resize((size, max(1, round(upright.height * size / upright.width))), Image.Resampling.LANCZOS)
                relative = Path(source).relative_to("media")
                destination = OUTPUT / relative.with_name(f"{relative.stem}-{width}.webp")
                destination.parent.mkdir(parents=True, exist_ok=True)
                preview.save(destination, "WEBP", quality=82, method=6)
                entry[label] = destination.relative_to(PUBLIC).as_posix()
                entry[label + "Width"] = size
                preview_bytes[width] += destination.stat().st_size
            manifest[source] = entry
            original_bytes += path.stat().st_size
    header = "// Generated by scripts/optimize-media.py. Originals remain available for full-size viewing.\n"
    header += "export const IMAGE_VARIANTS: Record<string, { width: number; height: number; small: string; smallWidth: number; large: string; largeWidth: number }> = "
    (ROOT / "src/data/imageVariants.ts").write_text(header + json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"images": len(manifest), "originalBytes": original_bytes, "previewBytes": preview_bytes}))


if __name__ == "__main__":
    main()
